body {
  margin: 0;
  font-family: "Segoe UI", "PingFang SC", "Microsoft YaHei", sans-serif;
  background:
    radial-gradient(1200px 600px at 10% -10%, #1c3a36 0%, transparent 55%),
    radial-gradient(900px 500px at 100% 0%, #2a2418 0%, transparent 50%),
    var(--bg);
  color: var(--text);
  line-height: 1.55;
}
.wrap { max-width: 960px; margin: 0 auto; padding: 40px 20px 80px; }
.brand {
  font-size: 13px; letter-spacing: 0.18em; text-transform: uppercase;
  color: var(--accent); font-weight: 600; margin-bottom: 8px;
}
h1 { font-size: 2rem; margin: 0 0 8px; font-weight: 700; }
.sub { color: var(--muted); margin-bottom: 28px; }
.hero {
  display: grid; grid-template-columns: 1.2fr 1fr; gap: 20px;
  margin-bottom: 28px;
}
@media (max-width: 720px) { .hero { grid-template-columns: 1fr; } }
