  --bg: #0f1419;
  --panel: #1a222c;
  --text: #e8eef4;
  --muted: #8b9aab;
  --accent: #2bb3a3;
  --accent2: #e8a838;
  --line: #2a3542;
  --ok: #3dba7a;
  --no: #e05d5d;
  --unk: #c4a35a;
}
