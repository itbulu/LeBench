  printf '%s\n' "${out}"
}

lzy_report_all() {
  local run_dir="${1:-${LZY_RUN_DIR}}"
  lzy_report_markdown "${run_dir}" >/dev/null
  lzy_report_html "${run_dir}" >/dev/null
}
